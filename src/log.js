'use strict';

/**
 * src/log.js —— 极简调试日志
 * ----------------------------------------------------------------------------
 * 为什么需要它：这个插件「取不到额度」时，用户能看到的只有一行中文提示；
 * 而真正的原因（401 / 超时 / 上游改结构）只有服务端知道。所以留一个开关：
 *
 *   QH_DEBUG=1  → 把每次上游失败的真实错误打到 stderr
 *
 * 默认静默：正常运行时控制台不输出任何东西，不会污染 DSH 日志。
 * 有意不记录 token / access / 邮箱等密文，只记错误对象本身。
 * ----------------------------------------------------------------------------
 */

/** 是否开启调试日志 */
function enabled() {
  return process.env.QH_DEBUG === '1';
}

/** 输出调试日志（默认静默） */
function debug(...args) {
  if (!enabled()) return;
  try {
    console.error('[quota-hub]', ...args);
  } catch (e) {
    /* 日志失败不能影响主流程 */
  }
}

module.exports = { debug, enabled };
